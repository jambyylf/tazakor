#!/usr/bin/env python3
"""ТазаКөр палитрасына WCAG 2.1 контраст тексеруі."""
import sys
try:
    sys.stdout.reconfigure(encoding="utf-8")   # Windows консолі кириллицаны шығара алуы үшін
except Exception:
    pass

def lum(h):
    h = h.lstrip('#')
    c = [int(h[i:i+2], 16)/255 for i in (0, 2, 4)]
    c = [v/12.92 if v <= 0.04045 else ((v+0.055)/1.055)**2.4 for v in c]
    return 0.2126*c[0] + 0.7152*c[1] + 0.0722*c[2]

def ratio(a, b):
    la, lb = lum(a), lum(b)
    if la < lb: la, lb = lb, la
    return (la+0.05)/(lb+0.05)

P = {
    "bg":       "#12131F",   # негізгі қою фон
    "surface":  "#1C1E2E",   # панель / карточка
    "border":   "#6B7192",   # интерактив элементтің шекарасы, фокус сақинасы
    "accent":   "#BB5BFA",   # негізгі акцент (логотиптің күлгін ұшы)
    "accent2":  "#14A5F1",   # логотип градиентінің көк ұшы (тек логотип/безендіру)
    "text":     "#F3F4F9",   # негізгі мәтін
    "muted":    "#9AA0B8",   # солғын мәтін
    "success":  "#34D399",   # сәтті күй
    "error":    "#FF7A7A",   # қате күй
}

# (атауы, алдыңғы, артқы, талап, WCAG критерийі)
CHECKS = [
    ("Негізгі мәтін",              "text",    "bg",      4.5, "1.4.3"),
    ("Негізгі мәтін (панельде)",   "text",    "surface", 4.5, "1.4.3"),
    ("Солғын мәтін",               "muted",   "bg",      4.5, "1.4.3"),
    ("Солғын мәтін (панельде)",    "muted",   "surface", 4.5, "1.4.3"),
    ("Акцент мәтін/белгіше",       "accent",  "bg",      4.5, "1.4.3"),
    ("Сәтті күй мәтіні",           "success", "bg",      4.5, "1.4.3"),
    ("Қате күй мәтіні",            "error",   "bg",      4.5, "1.4.3"),
    ("Түйме мәтіні (акцент фонда)","bg",      "accent",  4.5, "1.4.3"),
    ("Өріс шекарасы / фокус",      "border",  "surface", 3.0, "1.4.11"),
    ("Өріс шекарасы / фокус (фон)","border",  "bg",      3.0, "1.4.11"),
]

w = max(len(n) for n, *_ in CHECKS)
print(f"{'Тексеру':<{w}}  {'алдыңғы':<9} {'артқы':<9} {'қатынас':>9}  {'талап':>6}  {'WCAG':<7} нәтиже")
print("─"*(w+56))
fails = 0
for name, fg, bg, need, crit in CHECKS:
    r = ratio(P[fg], P[bg]); ok = r >= need; fails += not ok
    print(f"{name:<{w}}  {P[fg]:<9} {P[bg]:<9} {r:>8.2f}:1  {need:>5.1f}  {crit:<7} {'✓ OK' if ok else '✗ ЖЕТПЕЙДІ'}")

print()
print(f"Ақпарат үшін (талап емес): панель мен фон айырмасы "
      f"{ratio(P['surface'], P['bg']):.2f}:1 — бұл тек қабаттарды бөлу, WCAG оған шек қоймайды.")
print(f"Ақпарат үшін: логотиптің көк ұшы {P['accent2']} қою фонда {ratio(P['accent2'], P['bg']):.2f}:1.")
print()
print("AA талабы: қалыпты мәтін 4.5:1 (1.4.3), интерактив элемент шекарасы 3:1 (1.4.11).")
print("ҚОРЫТЫНДЫ:", "барлық тексеру өтті ✓" if not fails else f"{fails} тексеру өтпеді ✗")
sys.exit(1 if fails else 0)
